from fastapi import APIRouter, Depends, HTTPException, status

from app.auth.dependencies import get_current_user
from app.ml.disease_prediction.predictor import get_predictor
from app.schemas.prediction import (
    DiseasePredictionRequest,
    DiseasePredictionResponse,
)
from app.services.gemini_service import (
    generate_medical_explanation,
)


router = APIRouter(
    prefix="/predictions",
    tags=["Disease Prediction"],
)


@router.post(
    "/disease",
    response_model=DiseasePredictionResponse,
    status_code=status.HTTP_200_OK,
)
def predict_disease(
    request: DiseasePredictionRequest,
    current_user=Depends(get_current_user),
):
    predictor = get_predictor()

    # ---------------------------------------------------------
    # Step 1: Generate predictions using the ML model
    # ---------------------------------------------------------

    try:
        result = predictor.predict(
            symptoms=request.symptoms,
            top_k=request.top_k,
        )

    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(exc),
        ) from exc

    # ---------------------------------------------------------
    # Step 2: Extract predictions from predictor result
    # ---------------------------------------------------------

    predictions_for_gemini = [
        {
            "disease": item["disease"],
        }
        for item in result["results"]
    ]

    # ---------------------------------------------------------
    # Step 3: Generate Gemini explanation
    # ---------------------------------------------------------

    try:
        explanation = generate_medical_explanation(
            symptoms=request.symptoms,
            predictions=predictions_for_gemini,
        )

    except Exception as exc:
        print(f"Gemini explanation failed: {exc}")

        explanation = (
            "The AI explanation service is temporarily "
            "unavailable. The candidate conditions shown "
            "above were generated by the disease prediction "
            "model and should not be considered a medical "
            "diagnosis."
        )

    # ---------------------------------------------------------
    # Step 4: Return ML results + Gemini explanation
    # ---------------------------------------------------------

    return DiseasePredictionResponse(
        results=result["results"],
        top_score=result["top_score"],
        top_two_margin=result["top_two_margin"],
        needs_caution=result["needs_caution"],
        message=result["message"],
        explanation=explanation,
        confidence_level=result["confidence_level"],
    )