URGENT_KEYWORDS = [
    "chest pain",
    "severe chest pain",
    "difficulty breathing",
    "can't breathe",
    "cannot breathe",
    "shortness of breath",
    "severe bleeding",
    "uncontrolled bleeding",
    "loss of consciousness",
    "fainted",
    "unconscious",
    "seizure",
    "stroke",
    "face drooping",
    "slurred speech",
    "sudden weakness",
    "severe allergic reaction",
    "anaphylaxis",
    "suicidal",
    "suicide",
    "overdose",
]


def detect_urgent_symptoms(message: str) -> bool:
    """
    Conservative safety check for potentially urgent
    symptom descriptions.

    This is NOT a medical diagnosis.
    """

    text = message.lower().strip()

    return any(
        keyword in text
        for keyword in URGENT_KEYWORDS
    )


